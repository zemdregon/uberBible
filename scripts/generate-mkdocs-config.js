#!/usr/bin/env node
'use strict';

/**
 * Write mkdocs.yml from mkdocs.base.yml + shallow nav of translation + study indexes.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MD_ROOT = path.join(ROOT, 'derived', 'md');
const STUDY_MD = path.join(ROOT, 'derived', 'study', 'md');
const BASE = path.join(ROOT, 'mkdocs.base.yml');
const OUT = path.join(ROOT, 'mkdocs.yml');

function translationTitle(id) {
  const readme = path.join(MD_ROOT, id, 'README.md');
  if (!fs.existsSync(readme)) return id;
  const m = /^translation_name:\s*(.+)$/m.exec(fs.readFileSync(readme, 'utf8'));
  if (!m) return id;
  let t = m[1].trim();
  if ((t.startsWith('"') && t.endsWith('"')) || (t.startsWith("'") && t.endsWith("'"))) {
    t = t.slice(1, -1);
  }
  return t || id;
}

function studyTitle(id) {
  const readme = path.join(STUDY_MD, id, 'README.md');
  if (!fs.existsSync(readme)) return id;
  const m = /^work_title:\s*(.+)$/m.exec(fs.readFileSync(readme, 'utf8'));
  if (!m) return id;
  let t = m[1].trim();
  if ((t.startsWith('"') && t.endsWith('"')) || (t.startsWith("'") && t.endsWith("'"))) {
    t = t.slice(1, -1);
  }
  return t || id;
}

function yamlQuote(s) {
  if (/^[A-Za-z0-9 _./:+'-]+$/.test(s) && !s.includes(': ')) return s;
  return JSON.stringify(s);
}

function main() {
  if (!fs.existsSync(BASE)) {
    console.error('Missing mkdocs.base.yml');
    process.exit(1);
  }
  const base = fs.readFileSync(BASE, 'utf8').replace(/\s*$/, '\n');

  const ids = fs
    .readdirSync(MD_ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(MD_ROOT, d.name, 'README.md')))
    .map((d) => d.name)
    .sort((a, b) => translationTitle(a).localeCompare(translationTitle(b), 'en'));

  const studyIds = fs.existsSync(STUDY_MD)
    ? fs
        .readdirSync(STUDY_MD, { withFileTypes: true })
        .filter((d) => d.isDirectory() && fs.existsSync(path.join(STUDY_MD, d.name, 'README.md')))
        .map((d) => d.name)
        .sort((a, b) => studyTitle(a).localeCompare(studyTitle(b), 'en'))
    : [];

  const navLines = ['nav:', '  - Home: README.md', '  - Translations:'];
  for (const id of ids) {
    navLines.push(`      - ${yamlQuote(translationTitle(id))}: ${id}/README.md`);
  }
  if (studyIds.length) {
    navLines.push('  - Study:');
    for (const id of studyIds) {
      navLines.push(`      - ${yamlQuote(studyTitle(id))}: study/${id}/README.md`);
    }
  }

  const out = `${base}\n# Generated by scripts/generate-mkdocs-config.js — do not hand-edit nav.\n${navLines.join('\n')}\n`;
  fs.writeFileSync(OUT, out);
  console.log(
    `Wrote ${path.relative(ROOT, OUT)} (${ids.length} translations, ${studyIds.length} study works in nav)`
  );
}

main();
